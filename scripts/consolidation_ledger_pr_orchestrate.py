#!/usr/bin/env python3
"""Idempotent bot-owned PR orchestration for the nightly ledger refresh (H7967).

The nightly job (``.github/workflows/consolidation-ledger-nightly.yml``) keeps
the required ``consolidation_ledger_refresh.py --check`` gate green: the gate
compares date stamps, so the ledger goes stale by the calendar alone and the
robot, not a human, pays the daily cost (MG ruling 16-09-2026). Delivery is
PR-first -- the job never pushes to ``main`` directly.

Before H7967 every changed run minted a NEW ``chore/ledger-refresh-YYYYMMDD``
branch and a NEW PR, so the recurring review cost grew by one PR per changed
night. This script replaces that with ONE refresh-owned rolling branch
(``chore/ledger-refresh``) and ONE open PR: the first changed run creates the
branch and PR; every later changed run rebuilds the single generator-owned
commit on the current ``main`` and replaces the branch tip via
``--force-with-lease``, which updates the SAME PR in place. A no-change run
opens nothing at all.

Fail-closed contract (offline fixtures:
``tests/test_consolidation_ledger_pr_orchestrate.py``):

* two changed runs reuse the same branch and the same PR -- the update path
  never calls ``gh pr create`` while the PR is open;
* a no-change run performs zero mutations and creates no PR;
* a refreshed diff touching anything outside the ledger fails closed before
  any git/gh mutation (the exact single-file scope guard);
* an unowned branch (tip commit lacking OWNER_MARKER) is never updated, and no
  command ever names any other branch or PR -- the only force in this script is
  a ``--force-with-lease`` whose lease names the rolling branch and the exact
  fetched tip SHA. Legacy dated refresh branches/PRs are left untouched;
  closing or deleting them is out of scope.

Ownership lease: a tip commit whose body carries OWNER_MARKER was written by
this generator (or its pre-H7967 dated-branch ancestor -- same marker line),
so replacing it is safe. A tip without the marker is somebody else's work on
the same name and the run fails closed instead of destroying it.

Exit codes: 0 = orchestrated (or nothing to do); 1 = fail closed.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from dataclasses import dataclass

LEDGER_REL = "sangram/editorial/data/consolidation_ledger.json"
ROLLING_BRANCH = "chore/ledger-refresh"
BASE_BRANCH = "main"
OWNER_MARKER = "Generated by .github/workflows/consolidation-ledger-nightly.yml."
COMMIT_TITLE = "chore(sangram): nightly consolidation_ledger.json refresh"
COMMIT_BODY = (
    OWNER_MARKER + "\n"
    "\n"
    "The ci.yml gate compares date stamps, so the ledger goes stale by\n"
    "the calendar; this keeps the required check green without spending\n"
    "a human pass on it.\n"
)
PR_BODY = (
    "Automated nightly refresh. The consolidation_ledger_refresh.py --check gate in ci.yml "
    "compares date stamps, so the ledger goes stale by the calendar and reds main with no "
    "code change.\n"
    "\n"
    "Scope is enforced by the workflow: the run fails rather than opening a PR if the "
    "refresh touches anything outside " + LEDGER_REL + ".\n"
    "\n"
    "This is the SINGLE rolling refresh PR (branch " + ROLLING_BRANCH + "): every later "
    "changed run replaces the one generator-owned commit via --force-with-lease and "
    "updates this same PR instead of opening a dated one.\n"
    "\n"
    "Merging this is routine. A substantive diff here - anything beyond date stamps - "
    "means the generator's inputs changed and deserves a real look.\n"
)


# --------------------------------------------------------------------------
# Pure planning core. RemoteState is what the probes saw; Plan is the decision.
# Nothing here shells out, so the whole contract is provable offline.
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class RemoteState:
    """What the read-only probes observed about this run and the remote."""

    changed_files: tuple  # worktree-vs-index diff, repo-relative
    branch_exists: bool  # rolling branch present on origin
    branch_tip_sha: str  # its tip SHA when it exists, else ""
    branch_tip_owned: bool  # tip commit body carries OWNER_MARKER
    open_pr: bool  # an open PR whose head is the rolling branch


@dataclass(frozen=True)
class Action:
    op: str  # noop | commit | push | push_lease | open_pr | auto_merge
    target: str = ""  # only ever ROLLING_BRANCH
    detail: str = ""


@dataclass(frozen=True)
class Plan:
    actions: tuple
    outcome: str  # noop | orchestrate | fail
    reason: str


def plan(state: RemoteState) -> Plan:
    """Decide the run's actions. Fail closed before any mutation is planned."""
    dirty = tuple(state.changed_files)
    foreign = tuple(f for f in dirty if f != LEDGER_REL)
    if foreign:
        return Plan((), "fail",
                    "out-of-scope diff (single-file guard): " + ", ".join(foreign))
    if not dirty:
        return Plan((Action("noop"),), "noop",
                    "ledger already current - nothing to open")
    if not state.branch_exists:
        return Plan((
            Action("commit", ROLLING_BRANCH, "new"),
            Action("push", ROLLING_BRANCH),
            Action("open_pr", ROLLING_BRANCH),
            Action("auto_merge", ROLLING_BRANCH),
        ), "orchestrate", "create rolling branch + PR")
    if not state.branch_tip_owned:
        return Plan((), "fail",
                    "rolling branch tip is not generator-owned (missing owner marker); "
                    "refusing to update")
    acts = [
        Action("commit", ROLLING_BRANCH, "reuse"),
        Action("push_lease", ROLLING_BRANCH, state.branch_tip_sha),
    ]
    if state.open_pr:
        acts.append(Action("noop", detail="PR already open - same branch and PR reused"))
    else:
        acts += [Action("open_pr", ROLLING_BRANCH), Action("auto_merge", ROLLING_BRANCH)]
    return Plan(tuple(acts), "orchestrate",
                "update rolling branch" + ("" if state.open_pr else " + open PR"))


# --------------------------------------------------------------------------
# Execution over an injectable runner (the tests record the exact commands).
# --------------------------------------------------------------------------

class SubprocessRunner:
    """Real git/gh invocations. argv form, never a shell string."""

    def run(self, tool, *args):
        p = subprocess.run([tool, *args], capture_output=True, text=True)
        return p.returncode, p.stdout, p.stderr


def _error(msg):
    if os.environ.get("GITHUB_ACTIONS") == "true":
        print(f"::error::{msg}")
    print(f"ERROR: {msg}", file=sys.stderr)


def _summary(msg):
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(msg + "\n")


def collect_state(runner):
    """Read-only probes. Returns (RemoteState, None) or (None, error)."""
    rc, out, err = runner.run("git", "diff", "--name-only")
    if rc != 0:
        return None, f"git diff --name-only failed: {err.strip()}"
    changed = tuple(line for line in out.splitlines() if line.strip())

    rc, out, err = runner.run("git", "ls-remote", "--heads", "origin", ROLLING_BRANCH)
    if rc != 0:
        return None, f"git ls-remote failed: {err.strip()}"
    lines = [line for line in out.splitlines() if line.strip()]
    if lines:
        tip_sha = lines[0].split()[0]
        branch_exists = True
    else:
        tip_sha, branch_exists = "", False

    owned = False
    if branch_exists:
        rc, _, err = runner.run("git", "fetch", "origin", ROLLING_BRANCH)
        if rc != 0:
            return None, f"git fetch of rolling branch failed: {err.strip()}"
        rc, out, err = runner.run("git", "log", "-1", "--format=%B", tip_sha)
        if rc != 0:
            return None, f"cannot read rolling tip commit: {err.strip()}"
        owned = OWNER_MARKER in out

    open_pr = False
    if branch_exists:
        rc, out, err = runner.run("gh", "pr", "list", "--head", ROLLING_BRANCH,
                                  "--state", "open", "--json", "number")
        if rc != 0:
            return None, f"gh pr list failed (branch/PR state unchecked): {err.strip()}"
        try:
            open_pr = bool(json.loads(out or "[]"))
        except json.JSONDecodeError:
            return None, f"unparseable gh pr list output: {out!r}"

    return RemoteState(changed, branch_exists, tip_sha, owned, open_pr), None


def execute(plan_, runner):
    """Carry out a plan. Every command names only the rolling branch (or HEAD)."""
    if plan_.outcome == "fail":
        _error(plan_.reason)
        _summary(f"❌ {plan_.reason}")
        return 1
    if plan_.outcome == "noop":
        print(plan_.reason)
        _summary(plan_.reason)
        return 0

    print(plan_.reason)
    for act in plan_.actions:
        if act.op == "noop":
            print(act.detail)
            continue
        if act.op == "commit":
            steps = [
                ("git", "config", "user.name", "github-actions[bot]"),
                ("git", "config", "user.email",
                 "41898282+github-actions[bot]@users.noreply.github.com"),
                ("git", "add", LEDGER_REL),
                ("git", "commit", "-m", COMMIT_TITLE, "-m", COMMIT_BODY),
            ]
        elif act.op == "push":
            steps = [("git", "push", "origin", f"HEAD:refs/heads/{ROLLING_BRANCH}")]
        elif act.op == "push_lease":
            # The ONLY force in this script: leased to the rolling branch and
            # the exact fetched tip. An unowned/diverged tip fails closed.
            steps = [("git", "push",
                      f"--force-with-lease=refs/heads/{ROLLING_BRANCH}:{act.detail}",
                      "origin", f"HEAD:refs/heads/{ROLLING_BRANCH}")]
        elif act.op == "open_pr":
            steps = [("gh", "pr", "create", "--base", BASE_BRANCH, "--head",
                      ROLLING_BRANCH, "--title", COMMIT_TITLE, "--body", PR_BODY)]
        elif act.op == "auto_merge":
            rc, _, err = runner.run("gh", "pr", "merge", "--auto", "--squash",
                                    ROLLING_BRANCH)
            if rc != 0:
                print(f"::warning::auto-merge not enabled; merge by hand when green "
                      f"({err.strip()})")
            continue
        else:
            _error(f"unknown action op: {act.op}")
            return 1
        for cmd in steps:
            rc, out, err = runner.run(*cmd)
            if rc != 0:
                _error(f"{cmd[0]} {cmd[1]} failed: {err.strip() or out.strip()}")
                return 1

    _summary(f"✅ {plan_.reason} (rolling branch `{ROLLING_BRANCH}`)")
    return 0


def main() -> int:
    runner = SubprocessRunner()
    state, err = collect_state(runner)
    if err:
        _error(err)
        return 1
    return execute(plan(state), runner)


if __name__ == "__main__":
    sys.exit(main())
